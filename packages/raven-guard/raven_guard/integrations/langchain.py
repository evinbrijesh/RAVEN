from uuid import UUID

from raven_guard.context import get_current_context
from raven_guard.errors import ApprovalRequiredError, PolicyViolationError
from raven_guard.gateway import PolicyGateway
from raven_guard.models import Decision, SecurityContext

try:
    from langchain_core.callbacks.base import BaseCallbackHandler
    from langchain_core.messages import BaseMessage, ToolMessage
    from langchain_core.runnables import RunnableConfig
    from langchain_core.tools import BaseTool, StructuredTool
    HAS_LANGCHAIN = True
except ImportError:
    HAS_LANGCHAIN = False
    BaseCallbackHandler = object  # type: ignore
    BaseMessage = object  # type: ignore
    ToolMessage = object  # type: ignore
    BaseTool = object  # type: ignore
    RunnableConfig = dict[str, Any]  # type: ignore


class RavenGuardToolNode:
    """Drop-in LangGraph ToolNode middleware enforcing fail-closed raven-guard policies.

    Intercepts tool calls generated by LLMs (AIMessage.tool_calls) and evaluates them against
    raven-policy.yaml before executing the underlying tools.

    Usage in LangGraph:
        from raven_guard.integrations import RavenGuardToolNode
        builder.add_node("tools", RavenGuardToolNode(tools, gateway=gateway))
    """

    def __init__(
        self,
        tools: Sequence[Any],
        gateway: PolicyGateway,
        context: SecurityContext | dict[str, Any] | None = None,
        on_violation: str | Callable[[Decision, dict[str, Any]], Any] = "raise",
        handle_tool_errors: bool = True,
    ) -> None:
        self.gateway = gateway
        self.default_context = SecurityContext.from_any(context) if context else None
        self.on_violation = on_violation
        self.handle_tool_errors = handle_tool_errors

        self.tools_by_name: dict[str, Any] = {}
        for t in tools:
            name = getattr(t, "name", getattr(t, "__name__", str(t)))
            self.tools_by_name[name] = t

    def _resolve_context(self, state: Any, config: dict[str, Any] | None) -> SecurityContext:
        """Extracts security context from config, state, or ambient contextvar."""
        if config and isinstance(config, dict):
            cfg_dict = config.get("configurable", {})
            if "security_context" in cfg_dict:
                return SecurityContext.from_any(cfg_dict["security_context"])
            if "context" in cfg_dict:
                return SecurityContext.from_any(cfg_dict["context"])

        if isinstance(state, dict):
            if "security_context" in state:
                return SecurityContext.from_any(state["security_context"])
            if "context" in state:
                return SecurityContext.from_any(state["context"])

        ambient = get_current_context()
        if ambient is not None:
            return ambient

        return self.default_context or SecurityContext()

    def _handle_denial(self, decision: Decision, call: dict[str, Any]) -> Any:
        tool_name = call.get("name", "")
        call_id = call.get("id", "")
        args = call.get("args", {})

        if self.on_violation == "return_message":
            return ToolMessage(
                content=f"Error: Tool invocation '{tool_name}' blocked by security policy: {decision.reason}",
                tool_call_id=call_id,
                name=tool_name,
                status="error",
            )
        if callable(self.on_violation):
            return self.on_violation(decision, call)

        # Default: fail-closed raise
        if decision.reason == "high_value_action:approval_required":
            raise ApprovalRequiredError(
                f"Action '{tool_name}' requires explicit human approval: {decision.reason}",
                tool=tool_name,
                reason=decision.reason,
                decision=decision,
                arguments=args,
            )
        raise PolicyViolationError(
            f"Policy violation on tool '{tool_name}': {decision.reason}",
            tool=tool_name,
            reason=decision.reason,
            decision=decision,
            arguments=args,
        )

    def __call__(self, state: Any, config: RunnableConfig | None = None) -> dict[str, Any]:
        """Callable signature for LangGraph node registration."""
        return self.invoke(state, config=config)

    def invoke(self, state: Any, config: RunnableConfig | None = None) -> dict[str, Any]:
        """Synchronously processes and authorizes tool calls from the last message in state."""
        ctx = self._resolve_context(state, config)
        messages = state["messages"] if isinstance(state, dict) and "messages" in state else state
        if not isinstance(messages, list) or not messages:
            return {"messages": []}

        last_msg = messages[-1]
        tool_calls = getattr(last_msg, "tool_calls", None) or []
        if not tool_calls and isinstance(last_msg, dict):
            tool_calls = last_msg.get("tool_calls", [])

        results = []
        for call in tool_calls:
            tool_name = call.get("name", "")
            args = call.get("args", {})
            call_id = call.get("id", "")

            decision = self.gateway.authorize(tool_name, args, ctx)
            if not decision.allowed:
                results.append(self._handle_denial(decision, call))
                continue

            tool = self.tools_by_name.get(tool_name)
            if tool is None:
                results.append(
                    ToolMessage(
                        content=f"Error: Tool '{tool_name}' not found",
                        tool_call_id=call_id,
                        name=tool_name,
                        status="error",
                    )
                )
                continue

            try:
                if hasattr(tool, "invoke"):
                    raw_out = tool.invoke(args, config=config)
                elif callable(tool):
                    raw_out = tool(**args)
                else:
                    raw_out = f"Unsupported tool execution for {tool_name}"

                content = raw_out if isinstance(raw_out, str) else str(raw_out)
                results.append(
                    ToolMessage(
                        content=content,
                        tool_call_id=call_id,
                        name=tool_name,
                    )
                )
            except Exception as exc:
                if not self.handle_tool_errors:
                    raise
                results.append(
                    ToolMessage(
                        content=f"Tool execution failed: {exc}",
                        tool_call_id=call_id,
                        name=tool_name,
                        status="error",
                    )
                )

        return {"messages": results}

    async def ainvoke(self, state: Any, config: RunnableConfig | None = None) -> dict[str, Any]:
        """Asynchronously processes and authorizes tool calls from the last message in state."""
        ctx = self._resolve_context(state, config)
        messages = state["messages"] if isinstance(state, dict) and "messages" in state else state
        if not isinstance(messages, list) or not messages:
            return {"messages": []}

        last_msg = messages[-1]
        tool_calls = getattr(last_msg, "tool_calls", None) or []
        if not tool_calls and isinstance(last_msg, dict):
            tool_calls = last_msg.get("tool_calls", [])

        results = []
        for call in tool_calls:
            tool_name = call.get("name", "")
            args = call.get("args", {})
            call_id = call.get("id", "")

            decision = self.gateway.authorize(tool_name, args, ctx)
            if not decision.allowed:
                results.append(self._handle_denial(decision, call))
                continue

            tool = self.tools_by_name.get(tool_name)
            if tool is None:
                results.append(
                    ToolMessage(
                        content=f"Error: Tool '{tool_name}' not found",
                        tool_call_id=call_id,
                        name=tool_name,
                        status="error",
                    )
                )
                continue

            try:
                if hasattr(tool, "ainvoke"):
                    raw_out = await tool.ainvoke(args, config=config)
                elif hasattr(tool, "invoke"):
                    raw_out = tool.invoke(args, config=config)
                elif inspect.iscoroutinefunction(tool):
                    raw_out = await tool(**args)
                elif callable(tool):
                    raw_out = tool(**args)
                else:
                    raw_out = f"Unsupported tool execution for {tool_name}"

                content = raw_out if isinstance(raw_out, str) else str(raw_out)
                results.append(
                    ToolMessage(
                        content=content,
                        tool_call_id=call_id,
                        name=tool_name,
                    )
                )
            except Exception as exc:
                if not self.handle_tool_errors:
                    raise
                results.append(
                    ToolMessage(
                        content=f"Tool execution failed: {exc}",
                        tool_call_id=call_id,
                        name=tool_name,
                        status="error",
                    )
                )

        return {"messages": results}


class RavenGuardCallbackHandler(BaseCallbackHandler):
    """LangChain CallbackHandler that enforces raven-guard authorization before tool starts."""

    raise_error: bool = True

    def __init__(
        self,
        gateway: PolicyGateway,
        context: SecurityContext | dict[str, Any] | None = None,
    ) -> None:
        self.gateway = gateway
        self.context = SecurityContext.from_any(context) if context else None

    def on_tool_start(
        self,
        serialized: dict[str, Any],
        input_str: str,
        *,
        run_id: UUID,
        parent_run_id: UUID | None = None,
        tags: list[str] | None = None,
        metadata: dict[str, Any] | None = None,
        inputs: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> None:
        """Invoked when a tool starts execution; aborts if unauthorized."""
        tool_name = serialized.get("name", "")
        call_args = inputs if isinstance(inputs, dict) else {}

        ctx = self.context or get_current_context() or SecurityContext()
        decision = self.gateway.authorize(tool_name, call_args, ctx)
        if not decision.allowed:
            if decision.reason == "high_value_action:approval_required":
                raise ApprovalRequiredError(
                    f"Action '{tool_name}' requires explicit human approval: {decision.reason}",
                    tool=tool_name,
                    reason=decision.reason,
                    decision=decision,
                    arguments=call_args,
                )
            raise PolicyViolationError(
                f"Policy violation on '{tool_name}': {decision.reason}",
                tool=tool_name,
                reason=decision.reason,
                decision=decision,
                arguments=call_args,
            )


# Alias for intuitive discovery
RavenToolInterceptor = RavenGuardCallbackHandler


def wrap_tool(
    tool_or_func: Any,
    gateway: PolicyGateway,
    context: SecurityContext | dict[str, Any] | None = None,
    tool_name: str | None = None,
    on_violation: str = "raise",
) -> Any:
    """Wraps a LangChain BaseTool or callable with fail-closed raven-guard authorization."""
    name = tool_name or getattr(tool_or_func, "name", getattr(tool_or_func, "__name__", "tool"))
    description = getattr(tool_or_func, "description", getattr(tool_or_func, "__doc__", "Guarded tool")) or ""

    def guarded_func(*args: Any, **kwargs: Any) -> Any:
        ctx = SecurityContext.from_any(context) if context else (get_current_context() or SecurityContext())
        call_kwargs = dict(kwargs)
        if args and hasattr(tool_or_func, "func") and callable(tool_or_func.func):
            try:
                sig = inspect.signature(tool_or_func.func)
                bound = sig.bind_partial(*args, **kwargs)
                bound.apply_defaults()
                call_kwargs = dict(bound.arguments)
            except (TypeError, ValueError):
                pass

        decision = gateway.authorize(name, call_kwargs, ctx)
        if not decision.allowed:
            if on_violation == "return_decision":
                return decision
            if decision.reason == "high_value_action:approval_required":
                raise ApprovalRequiredError(
                    f"Action '{name}' requires explicit human approval: {decision.reason}",
                    tool=name,
                    reason=decision.reason,
                    decision=decision,
                    arguments=call_kwargs,
                )
            raise PolicyViolationError(
                f"Policy violation on '{name}': {decision.reason}",
                tool=name,
                reason=decision.reason,
                decision=decision,
                arguments=call_kwargs,
            )

        if hasattr(tool_or_func, "func") and callable(tool_or_func.func):
            return tool_or_func.func(*args, **kwargs)
        if hasattr(tool_or_func, "invoke"):
            return tool_or_func.invoke(call_kwargs)
        return tool_or_func(*args, **kwargs)

    if HAS_LANGCHAIN and hasattr(StructuredTool, "from_function"):
        args_schema = getattr(tool_or_func, "args_schema", None)
        return StructuredTool.from_function(
            func=guarded_func,
            name=name,
            description=description,
            args_schema=args_schema,
        )

    return guarded_func
